import { forwardRef, createElement } from "react";

const createIcon = (name, iconNode) => {
  const IconComponent = forwardRef(({ size = 24, className = "", color = "currentColor", strokeWidth = 2, children, ...props }, ref) => {
    return createElement(
      "svg",
      {
        ref,
        xmlns: "http://www.w3.org/2000/svg",
        width: size,
        height: size,
        viewBox: "0 0 24 24",
        fill: "none",
        stroke: color,
        strokeWidth,
        strokeLinecap: "round",
        strokeLinejoin: "round",
        className: `lucide lucide-${name} ${className}`.trim(),
        ...props,
      },
      iconNode.map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs })),
      children
    );
  });
  IconComponent.displayName = name;
  return IconComponent;
};

